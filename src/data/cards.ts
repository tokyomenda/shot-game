export function shuffleDeck(previousId?: number): Card[] {
  const deck = [...cards];
  for (let i = deck.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }
  if (deck[0].id === previousId) [deck[0], deck[1]] = [deck[1], deck[0]];
  return deck;
}